import {
  invitationAction,
  invitationRequest,
  inviteAddressPath,
  invitationsPath,
  type Invitation,
  type InviteAddress,
  type Request,
} from "./session";

/** Premium family management API shared by the web and mobile clients. */
export const familyPath = "/api/v1/family/me";
export const familiesPath = "/api/v1/family";
export const householdInvitationsPath = (householdId: string) =>
  `/api/v1/family/${encodeURIComponent(householdId)}/invitations`;
export const householdInvitationPath = (
  householdId: string,
  invitationId: string,
) =>
  `${householdInvitationsPath(householdId)}/${encodeURIComponent(invitationId)}`;
export const householdMemberPath = (householdId: string, memberId: string) =>
  `/api/v1/family/${encodeURIComponent(householdId)}/members/${encodeURIComponent(memberId)}`;

export type Member = {
  id: string;
  state: string;
  delegationEnabled: boolean;
  version: number;
  permissionVersion: number;
};

export type Household = {
  id: string;
  /** OWNER lists the members; MEMBER sees the household without the member list. */
  role: "OWNER" | "MEMBER";
  additionalSeats: number;
  occupiedOrReserved: number;
  members: Member[];
};

export type HouseholdInvitation = {
  id: string;
  householdId: string;
  state: string;
  expiresAt: string;
};

const uuidPattern =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** The recipient code is the invitee's own code, generated by invite-address. */
export function isRecipientCode(value: string): boolean {
  return uuidPattern.test(value.trim());
}

export function freeSeats(household: Household): number {
  return Math.max(0, household.additionalSeats - household.occupiedOrReserved);
}

export function familyMessage(status: number): string {
  switch (status) {
    case 400:
    case 422:
      return "Confira o código do convidado.";
    case 401:
      return "Sua sessão expirou. Entre novamente.";
    case 403:
      return "Sua conta não pode gerenciar a família. Confira o plano Premium Família.";
    case 404:
      return "Família não encontrada.";
    case 409:
      return "Esta operação mudou de estado. Atualize a tela.";
    default:
      return "Não foi possível concluir a operação na família.";
  }
}

async function readFamily<T>(response: Response): Promise<T> {
  if (!response.ok) throw new Error(familyMessage(response.status));
  return (response.status === 204 ? undefined : await response.json()) as T;
}

/** Returns null when the account has no household yet (the API answers 404). */
export async function loadHousehold(
  request: Request,
  init?: RequestInit,
): Promise<Household | null> {
  const response = await request(familyPath, { ...init, method: "GET" });
  if (response.status === 404) return null;
  return readFamily<Household>(response);
}

export async function createHousehold(
  request: Request,
  init?: RequestInit,
): Promise<Household> {
  const response = await request(familiesPath, { ...init, method: "POST" });
  return readFamily<Household>(response);
}

export async function loadHouseholdInvitations(
  request: Request,
  householdId: string,
  init?: RequestInit,
): Promise<HouseholdInvitation[]> {
  const response = await request(householdInvitationsPath(householdId), {
    ...init,
    method: "GET",
  });
  return readFamily<HouseholdInvitation[]>(response);
}

export async function inviteMember(
  request: Request,
  householdId: string,
  recipientCode: string,
  idempotencyKey: string,
  init?: RequestInit,
): Promise<HouseholdInvitation> {
  const response = await request(householdInvitationsPath(householdId), {
    ...init,
    method: "POST",
    headers: {
      ...(init?.headers as Record<string, string> | undefined),
      "Content-Type": "application/json",
      "Idempotency-Key": idempotencyKey,
    },
    body: JSON.stringify({ recipientCode: recipientCode.trim() }),
  });
  return readFamily<HouseholdInvitation>(response);
}

export async function cancelInvitation(
  request: Request,
  householdId: string,
  invitationId: string,
  init?: RequestInit,
): Promise<void> {
  const response = await request(
    householdInvitationPath(householdId, invitationId),
    {
      ...init,
      method: "DELETE",
    },
  );
  await readFamily<void>(response);
}

export async function removeMember(
  request: Request,
  householdId: string,
  member: Member,
  init?: RequestInit,
): Promise<void> {
  const query = new URLSearchParams({
    expectedVersion: String(member.version),
  });
  const response = await request(
    `${householdMemberPath(householdId, member.id)}?${query}`,
    { ...init, method: "DELETE" },
  );
  await readFamily<void>(response);
}

export function memberStateLabel(state: string): string {
  return state === "ACTIVE" ? "Ativo" : "Inativo";
}

export function invitationStateLabel(state: string): string {
  return state === "PENDING" ? "Pendente" : "Encerrado";
}

/** Idempotency key for invitations; falls back where crypto.randomUUID is absent (Hermes). */
export function newIdempotencyKey(): string {
  const cryptoApi = (
    globalThis as {
      crypto?: {
        randomUUID?: () => string;
        getRandomValues?: (array: Uint8Array) => Uint8Array;
      };
    }
  ).crypto;
  if (cryptoApi?.randomUUID) return cryptoApi.randomUUID();
  const bytes = new Uint8Array(16);
  if (cryptoApi?.getRandomValues) cryptoApi.getRandomValues(bytes);
  else
    for (let index = 0; index < bytes.length; index += 1)
      bytes[index] = Math.floor(Math.random() * 256);
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) =>
    byte.toString(16).padStart(2, "0"),
  ).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function isMemberHousehold(household: Household): boolean {
  return household.role === "MEMBER";
}

export function canRespondToInvitation(invitation: Invitation): boolean {
  return invitation.state === "PENDING";
}

/** Invitations received by the caller, as the guest sees them (same endpoint as the restricted screen). */
export function loadReceivedInvitations(
  request: Request,
  init?: RequestInit,
): Promise<Invitation[]> {
  return invitationRequest<Invitation[]>(request, invitationsPath, {
    ...init,
    method: "GET",
  });
}

/** The caller's own invitation code, to be given to the holder who invites them. */
export function createInviteAddress(
  request: Request,
  init?: RequestInit,
): Promise<InviteAddress> {
  return invitationRequest<InviteAddress>(request, inviteAddressPath, {
    ...init,
    method: "POST",
  });
}

export async function respondToInvitation(
  request: Request,
  invitationId: string,
  action: "accept" | "decline",
  init?: RequestInit,
): Promise<void> {
  await invitationRequest<unknown>(
    request,
    invitationAction(invitationId, action),
    {
      ...init,
      method: "POST",
    },
  );
}

export type FamilyView = "loading" | "member" | "owner" | "guest" | "premium-without-family";

/**
 * Decides which family view a signed-in user sees. Shared by the web and mobile
 * screens so both platforms show the same state for the same data.
 */
export function familyView(
  subscription: { premiumFamily: boolean } | undefined,
  household: Household | null | undefined,
): FamilyView {
  if (subscription === undefined || household === undefined) return "loading";
  if (household !== null) return isMemberHousehold(household) ? "member" : "owner";
  return subscription.premiumFamily ? "premium-without-family" : "guest";
}

